// Issue #1346: spec hygiene. Every spec in `docs/specs` is named `NNNN-kebab-title.md`,
// numbers are unique, it has a `Status:` and a `Zweck:` line, and `INDEX.md` is the
// generated table of all specs. Usage:
//   node scripts/check-spec-index.mjs [--dir <path>] [--index <path>] [--write-index]
// Text based, no dependencies.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, "..");

export const INDEX_HEADER = "<!-- generated by scripts/check-spec-index.mjs --write-index, do not edit -->";
const NAME_RE = /^(\d{4})-[a-z0-9]+(?:-[a-z0-9]+)*\.md$/;
const SPECIAL = new Set(["README.md", "INDEX.md"]);
const FIELD_RE = /^[\p{Lu}][\p{L}]*:/u;

/** Value of a header field (`Status:`, `Zweck:`), with continuation lines joined; null when missing/empty. */
function field(lines, key) {
  const i = lines.findIndex((l) => l.startsWith(`${key}:`));
  if (i < 0) return null;
  const parts = [lines[i].slice(key.length + 1).trim()];
  for (const l of lines.slice(i + 1)) {
    if (l.trim() === "" || l.startsWith("#") || FIELD_RE.test(l)) break;
    parts.push(l.trim());
  }
  const value = parts.join(" ").trim();
  return value === "" ? null : value;
}

/** `{ number, title, status, purpose }`; `status` and `purpose` are null when missing. */
export function parseSpec(name, content) {
  const lines = content.split("\n");
  const heading = lines.find((l) => /^# /.test(l)) ?? "";
  const title =
    heading
      .replace(/^# /, "")
      .replace(/^(Spec\s+)?\d{4}\s*(?:[—–]|-)\s*/, "")
      .trim() || name.replace(/\.md$/, "");
  const rawStatus = field(lines, "Status");
  // Keep the status word(s); drop trailing detail such as "(…)", "· Issue: …" or "; …".
  const status = rawStatus === null ? null : rawStatus.split(/ \(|\s·|;/)[0].trim() || null;
  return { number: name.slice(0, 4), title, status, purpose: field(lines, "Zweck") };
}

const cell = (s) => s.replace(/\|/g, "\\|");

/** Rendered `INDEX.md`; `files` maps file name to content. */
export function buildIndex(files) {
  const rows = [...files]
    .filter(([name]) => NAME_RE.test(name))
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([name, content]) => {
      const s = parseSpec(name, content);
      return `| ${s.number} | [${cell(s.title)}](${name}) | ${cell(s.status ?? "?")} | ${cell(s.purpose ?? "?")} |`;
    });
  return [
    "# Spec index",
    "",
    INDEX_HEADER,
    "",
    "| Number | Title | Status | Purpose |",
    "| --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
}

/** Problems as `{ file, message }`; `index` is the current INDEX.md content or null. */
export function findSpecProblems(files, index) {
  const problems = [];
  const byNumber = new Map();
  for (const name of [...files.keys()].sort()) {
    if (SPECIAL.has(name)) continue;
    const m = name.match(NAME_RE);
    if (!m) {
      problems.push({ file: name, message: "file name does not match NNNN-kebab-title.md" });
      continue;
    }
    byNumber.set(m[1], [...(byNumber.get(m[1]) ?? []), name]);
  }
  for (const [num, names] of byNumber) {
    if (names.length > 1) {
      for (const n of names) problems.push({ file: n, message: `duplicate spec number ${num}: ${names.join(", ")}` });
    }
    for (const name of names) {
      const s = parseSpec(name, files.get(name));
      if (!s.status) problems.push({ file: name, message: "missing `Status:` line" });
      if (!s.purpose) problems.push({ file: name, message: "missing `Zweck:` line" });
    }
  }
  const hint = "run `node scripts/check-spec-index.mjs --write-index`";
  if (index === null) {
    problems.push({ file: "INDEX.md", message: `missing; ${hint}` });
  } else if (index !== buildIndex(files)) {
    problems.push({ file: "INDEX.md", message: `out of date; ${hint}` });
  }
  return problems;
}

function readDir(dir, indexPath) {
  const files = new Map();
  for (const name of fs.readdirSync(dir)) {
    if (name.endsWith(".md") && name !== "INDEX.md" && path.resolve(dir, name) !== path.resolve(indexPath)) files.set(name, fs.readFileSync(path.join(dir, name), "utf8").replace(/\r\n/g, "\n"));
  }
  return files;
}

/** Check a directory; with `writeIndex` regenerate the index first. */
export function checkSpecIndex({ dir = path.join(REPO_ROOT, "docs", "specs"), index, writeIndex = false } = {}) {
  const indexPath = index ?? path.join(dir, "INDEX.md");
  const files = readDir(dir, indexPath);
  if (writeIndex) fs.writeFileSync(indexPath, buildIndex(files));
  const current = fs.existsSync(indexPath) ? fs.readFileSync(indexPath, "utf8").replace(/\r\n/g, "\n") : null;
  return findSpecProblems(files, current);
}

function main() {
  const args = process.argv.slice(2);
  const opts = { writeIndex: args.includes("--write-index") };
  for (const flag of ["--dir", "--index"]) {
    const at = args.indexOf(flag);
    if (at >= 0) {
      if (!args[at + 1]) {
        console.error(`${flag} needs a value`);
        process.exitCode = 2;
        return;
      }
      opts[flag.slice(2)] = path.resolve(args[at + 1]);
    }
  }
  const problems = checkSpecIndex(opts);
  for (const p of problems) console.error(`${p.file}: ${p.message}`);
  if (problems.length > 0) process.exitCode = 1;
  else console.log("Spec index check passed.");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
