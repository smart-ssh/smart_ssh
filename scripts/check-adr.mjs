// Issue #850: ADR hygiene. Every file in `docs/adr` is named `NNNN-kebab-title.md`,
// numbers are unique, a `## Status` section starts with one of Proposed, Accepted,
// `Superseded by NNNN` (an existing ADR) or Deprecated, and `INDEX.md` is the
// generated table of all ADRs. Usage:
//   node scripts/check-adr.mjs [--dir <path>] [--index <path>] [--write-index]
// Text based, no dependencies.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, "..");

export const INDEX_HEADER = "<!-- generated by scripts/check-adr.mjs --write-index, do not edit -->";
const NAME_RE = /^(\d{4})-[a-z0-9]+(?:-[a-z0-9]+)*\.md$/;
const STATUS_RE = /^(Proposed|Accepted|Deprecated|Superseded by (\d{4}))(?![\p{L}\p{N}])/u;
const SPECIAL = new Set(["README.md", "INDEX.md"]);

/** `{ number, title, status, successor }` of one ADR; `status` is null when missing/unknown. */
export function parseAdr(name, content) {
  const lines = content.split("\n");
  const heading = lines.find((l) => /^# /.test(l)) ?? "";
  const title =
    heading
      .replace(/^# /, "")
      .replace(/^(ADR\s+)?\d{4}\s*(?:[—–]|-)\s*/, "")
      .trim() || name.replace(/\.md$/, "");
  let status = null;
  let successor = null;
  const i = lines.findIndex((l) => /^## Status\s*$/.test(l));
  if (i >= 0) {
    const first = lines.slice(i + 1).find((l) => l.trim() !== "" && !l.startsWith("#"));
    const m = first?.trim().match(STATUS_RE);
    if (m) {
      status = m[1];
      successor = m[2] ?? null;
    }
  }
  return { number: name.slice(0, 4), title, status, successor };
}

/** Rendered `INDEX.md`; `files` maps file name to content. */
export function buildIndex(files) {
  const rows = [...files]
    .filter(([name]) => NAME_RE.test(name))
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([name, content]) => {
      const a = parseAdr(name, content);
      const title = a.title.replace(/\|/g, "\\|");
      return `| ${a.number} | ${title} | ${a.status ?? "?"} | [${name}](${name}) |`;
    });
  return [
    "# ADR index",
    "",
    INDEX_HEADER,
    "",
    "| Number | Title | Status | File |",
    "| --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
}

/** Problems as `{ file, message }`; `index` is the current INDEX.md content or null. */
export function findAdrProblems(files, index) {
  const problems = [];
  const byNumber = new Map();
  for (const name of [...files.keys()].sort()) {
    if (SPECIAL.has(name)) continue;
    const m = name.match(NAME_RE);
    if (!m) {
      problems.push({ file: name, message: "file name does not match NNNN-kebab-title.md" });
      continue;
    }
    byNumber.set(m[1], [...(byNumber.get(m[1]) ?? []), name]);
  }
  for (const [num, names] of byNumber) {
    if (names.length > 1) {
      for (const n of names) problems.push({ file: n, message: `duplicate ADR number ${num}: ${names.join(", ")}` });
    }
  }
  for (const [num, names] of byNumber) {
    for (const name of names) {
      const a = parseAdr(name, files.get(name));
      if (!a.status) {
        problems.push({
          file: name,
          message:
            "missing or unknown status: needs a `## Status` section whose first line starts with Proposed, Accepted, Superseded by NNNN or Deprecated",
        });
      } else if (a.successor && !byNumber.has(a.successor)) {
        problems.push({ file: name, message: `Superseded by ${a.successor}: no ADR with that number` });
      } else if (a.successor === num) {
        problems.push({ file: name, message: "an ADR cannot supersede itself" });
      }
    }
  }
  if (index === null) {
    problems.push({ file: "INDEX.md", message: "missing; run `node scripts/check-adr.mjs --write-index`" });
  } else if (index !== buildIndex(files)) {
    problems.push({ file: "INDEX.md", message: "out of date; run `node scripts/check-adr.mjs --write-index`" });
  }
  return problems;
}

function readDir(dir, indexPath) {
  const files = new Map();
  for (const name of fs.readdirSync(dir)) {
    if (name.endsWith(".md") && name !== "INDEX.md" && path.resolve(dir, name) !== path.resolve(indexPath)) files.set(name, fs.readFileSync(path.join(dir, name), "utf8"));
  }
  return files;
}

/** Check a directory; with `writeIndex` regenerate the index first. */
export function checkAdr({ dir = path.join(REPO_ROOT, "docs", "adr"), index, writeIndex = false } = {}) {
  const indexPath = index ?? path.join(dir, "INDEX.md");
  const files = readDir(dir, indexPath);
  if (writeIndex) fs.writeFileSync(indexPath, buildIndex(files));
  const current = fs.existsSync(indexPath) ? fs.readFileSync(indexPath, "utf8") : null;
  return findAdrProblems(files, current);
}

function main() {
  const args = process.argv.slice(2);
  const opts = { writeIndex: args.includes("--write-index") };
  for (const flag of ["--dir", "--index"]) {
    const at = args.indexOf(flag);
    if (at >= 0) {
      if (!args[at + 1]) {
        console.error(`${flag} needs a value`);
        process.exitCode = 2;
        return;
      }
      opts[flag.slice(2)] = path.resolve(args[at + 1]);
    }
  }
  const problems = checkAdr(opts);
  for (const p of problems) console.error(`${p.file}: ${p.message}`);
  if (problems.length > 0) process.exitCode = 1;
  else console.log("ADR check passed.");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
